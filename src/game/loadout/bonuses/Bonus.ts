/**
 * Bonus — единый контракт всех временных бонусов игрока.
 *
 * Бонус — это усиление, которое живёт ограниченное время и тикает
 * каждый кадр: темп огня, дополнительные стволы, рывок.
 *
 * Построено по образцу модуля оружия (src/game/weapons):
 *   • каждый бонус — отдельный класс со своей логикой (SRP);
 *   • добавить новый бонус — новый класс + запись в реестре (OCP);
 *   • бонус не знает о других системах и получает всё через контракт.
 *
 * Мгновенные бонусы (ремонт, минерал) состояния не имеют — они
 * обрабатываются ApplyPickupSystem, а здесь лишь мигают в HUD
 * (см. INSTANT_BONUS_FLASH в BonusRegistry).
 */

import type { LoadoutSlotMeta } from "../LoadoutTypes";

/** Идентификаторы временных бонусов. */
export type BonusId = "rate" | "guns";

/** Идентификаторы мгновенных бонусов (без состояния и таймера). */
export type InstantBonusId = "heal" | "mineral";

/** Все виды бонусов, видимых в строке снаряжения. */
export type BonusKind = BonusId | InstantBonusId;

/** Оформление слота бонуса в строке снаряжения. */
export type BonusMeta = LoadoutSlotMeta & {
  /** Вид бонуса. */
  kind: BonusKind;
  /** Длительность в секундах (0 — мгновенный бонус). */
  duration: number;
};

/**
 * Снимок текущих временных бонусов для потребителей:
 * модуль оружия (rateMult, extraBarrels) и рендер игрока (rateT).
 */
export interface PlayerBonuses {
  /** Множитель темпа стрельбы от бонуса «темп огня» (1 + стек). */
  rateMult: number;
  /** Остаток бонуса «темп огня», секунды (кольцо в рендере). */
  rateT: number;
  /** Временно добавленные стволы пушки. */
  extraBarrels: number;
}

/**
 * Единый контракт временных бонусов.
 *
 * Каждый бонус сам знает, что он делает при активации (подборе пикапа)
 * и как тикает его таймер. Конкретное значение для оружия (например,
 * множитель темпа огня) бонус отдаёт узким методом собственного класса —
 * так же, как WeaponManager раскладывает апгрейды по свойствам оружия.
 */
export interface Bonus {
  /** Идентификатор вида бонуса. */
  readonly id: BonusId;
  /** Оформление слота бонуса в строке снаряжения. */
  readonly meta: BonusMeta;

  /** Активен ли бонус прямо сейчас. */
  isActive(): boolean;

  /** Остаток времени действия, секунды. */
  getRemaining(): number;

  /** Заполнение кольца в HUD, 0..1 (остаток / длительность). */
  getProgress(): number;

  /** Активировать бонус — подбор пикапа. Повторный подбор усиливает. */
  activate(): void;

  /** Тик таймера бонуса. */
  update(dt: number): void;

  /** Сбросить состояние бонуса — начало забега. */
  reset(): void;
}