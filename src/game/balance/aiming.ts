/* ============================================================
   Lead prediction & shot dispersion — настройки упреждающего
   прицела. Шансы попадания игрока и врагов — в accuracy.ts.
   ============================================================ */

/* --------------------------- Время полёта снаряда --------------------------- */

/** Минимальное расчётное время полёта, секунды. */
export const LEAD_MIN_TIME = 0.01;

/**
 * Максимальное расчётное время полёта, секунды.
 * Дальше упреждение не считается: за это время цель успевает повернуть,
 * и линейный прогноз теряет смысл.
 */
export const LEAD_MAX_TIME = 2.0;

/* ------------------------------ Вероятность ------------------------------ */

/**
 * Жёсткий потолок шанса попадания. Даже если в балансе линии задано 1.0,
 * выстрел никогда не становится гарантированным.
 */
export const AIM_CHANCE_CEILING = 0.95;

/** Минимальный шанс попадания: совсем слепой выстрел тоже иногда задевает. */
export const AIM_CHANCE_FLOOR = 0.05;

/* --------------------------- Конус рассеивания --------------------------- */

/**
 * Минимальный полуугол конуса рассеивания, радианы.
 * Не даёт высокой точности схлопнуть разброс в идеальную линию.
 */
export const AIM_MIN_SPREAD = 0.012;

/** Максимальный полуугол конуса рассеивания, радианы. */
export const AIM_MAX_SPREAD = 0.55;

/**
 * Недобор точности из-за манёвра цели: прогноз линеен, а цель за время полёта
 * меняет курс. Коэффициент > 1 расширяет конус, поэтому фактическое попадание
 * всегда ниже номинального шанса.
 */
export const AIM_MANEUVER_FACTOR = 1.15;
